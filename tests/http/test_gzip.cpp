#include "fw/http/gzip.hpp"

#include <gtest/gtest.h>

#include <initializer_list>
#include <string>

namespace {

std::string bytes(std::initializer_list<unsigned char> data) {
    return std::string{reinterpret_cast<char const*>(data.begin()), data.size()};
}

} // namespace

TEST(HttpGzip, DecompressesHelloWorld) {
    auto const compressed = bytes({0x1f, 0x8b, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xff, 0xcb,
                                   0x48, 0xcd, 0xc9, 0xc9, 0x57, 0x28, 0xcf, 0x2f, 0xca, 0x49, 0x01,
                                   0x00, 0x85, 0x11, 0x4a, 0x0d, 0x0b, 0x00, 0x00, 0x00});
    auto const result = fw::http::gzip_decompress(compressed);
    ASSERT_TRUE(result.has_value());
    EXPECT_EQ(*result, "hello world");
}

TEST(HttpGzip, DecompressesConcatenatedMembers) {
    auto const compressed =
        bytes({0x1f, 0x8b, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xff, 0xcb, 0x48, 0xcd,
               0xc9, 0xc9, 0x57, 0x00, 0x00, 0xf6, 0xf9, 0x81, 0xed, 0x06, 0x00, 0x00, 0x00,
               0x1f, 0x8b, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xff, 0x2b, 0xcf, 0x2f,
               0xca, 0x49, 0x01, 0x00, 0x43, 0x11, 0x77, 0x3a, 0x05, 0x00, 0x00, 0x00});
    auto const result = fw::http::gzip_decompress(compressed);
    ASSERT_TRUE(result.has_value());
    EXPECT_EQ(*result, "hello world");
}

TEST(HttpGzip, RejectsCorruptInput) {
    auto const result = fw::http::gzip_decompress("this is not a gzip stream");
    EXPECT_FALSE(result.has_value());
}
